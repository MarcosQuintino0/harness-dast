-- Esquema da Clinica Piloto. Valido em Oracle 19c+/Free 23ai e em H2 (MODE=Oracle).
-- Toda tabela tem CREATED_BY e CREATED_AT: e o que permite ao cleanup/cleanup.sql
-- apagar somente o que as contas de teste criaram durante uma execucao.
-- Os ids vem de SEQ_CLINICA (a partir de 1000); linhas de seed usam ids abaixo disso.

CREATE SEQUENCE SEQ_CLINICA START WITH 1000 INCREMENT BY 1;

CREATE TABLE CONVENIO (
  ID                       NUMBER(19)         NOT NULL,
  CODIGO                   VARCHAR2(8 CHAR)   NOT NULL,
  NOME                     VARCHAR2(80 CHAR)  NOT NULL,
  TIPO                     VARCHAR2(20 CHAR)  NOT NULL,
  COPARTICIPACAO_PERCENTUAL NUMBER(3)         NOT NULL,
  ATIVO                    NUMBER(1)          DEFAULT 1 NOT NULL,
  CREATED_BY               VARCHAR2(60 CHAR)  NOT NULL,
  CREATED_AT               TIMESTAMP          NOT NULL,
  CONSTRAINT PK_CONVENIO PRIMARY KEY (ID),
  CONSTRAINT UQ_CONVENIO_CODIGO UNIQUE (CODIGO),
  CONSTRAINT CK_CONVENIO_TIPO CHECK (TIPO IN ('INDIVIDUAL', 'EMPRESARIAL', 'PUBLICO')),
  CONSTRAINT CK_CONVENIO_COPART CHECK (COPARTICIPACAO_PERCENTUAL BETWEEN 0 AND 100)
);

CREATE TABLE MEDICO (
  ID            NUMBER(19)         NOT NULL,
  NOME          VARCHAR2(100 CHAR) NOT NULL,
  CRM           VARCHAR2(10 CHAR)  NOT NULL,
  ESPECIALIDADE VARCHAR2(30 CHAR)  NOT NULL,
  CREATED_BY    VARCHAR2(60 CHAR)  NOT NULL,
  CREATED_AT    TIMESTAMP          NOT NULL,
  CONSTRAINT PK_MEDICO PRIMARY KEY (ID),
  CONSTRAINT UQ_MEDICO_CRM UNIQUE (CRM)
);

CREATE TABLE PACIENTE (
  ID              NUMBER(19)          NOT NULL,
  NOME            VARCHAR2(100 CHAR)  NOT NULL,
  CPF             VARCHAR2(11 CHAR)   NOT NULL,
  EMAIL           VARCHAR2(120 CHAR)  NOT NULL,
  DATA_NASCIMENTO DATE                NOT NULL,
  SEXO            VARCHAR2(20 CHAR)   NOT NULL,
  TELEFONE        VARCHAR2(11 CHAR),
  CONVENIO_ID     NUMBER(19)          NOT NULL,
  NOTAS_INTERNAS  VARCHAR2(400 CHAR),
  CREATED_BY      VARCHAR2(60 CHAR)   NOT NULL,
  CREATED_AT      TIMESTAMP           NOT NULL,
  CONSTRAINT PK_PACIENTE PRIMARY KEY (ID),
  CONSTRAINT UQ_PACIENTE_CPF UNIQUE (CPF),
  CONSTRAINT UQ_PACIENTE_EMAIL UNIQUE (EMAIL),
  CONSTRAINT FK_PACIENTE_CONVENIO FOREIGN KEY (CONVENIO_ID) REFERENCES CONVENIO (ID)
);

CREATE TABLE USUARIO (
  ID            NUMBER(19)         NOT NULL,
  USERNAME      VARCHAR2(60 CHAR)  NOT NULL,
  PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
  PAPEL         VARCHAR2(20 CHAR)  NOT NULL,
  NOME_EXIBICAO VARCHAR2(100 CHAR),
  TELEFONE      VARCHAR2(11 CHAR),
  PACIENTE_ID   NUMBER(19),
  MEDICO_ID     NUMBER(19),
  CREATED_BY    VARCHAR2(60 CHAR)  NOT NULL,
  CREATED_AT    TIMESTAMP          NOT NULL,
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
  CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
  CONSTRAINT CK_USUARIO_PAPEL CHECK (PAPEL IN ('paciente', 'medico', 'admin')),
  CONSTRAINT FK_USUARIO_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES PACIENTE (ID),
  CONSTRAINT FK_USUARIO_MEDICO FOREIGN KEY (MEDICO_ID) REFERENCES MEDICO (ID)
);

CREATE TABLE CONSULTA (
  ID          NUMBER(19)         NOT NULL,
  PACIENTE_ID NUMBER(19)         NOT NULL,
  MEDICO_ID   NUMBER(19)         NOT NULL,
  DATA_HORA   TIMESTAMP          NOT NULL,
  MOTIVO      VARCHAR2(200 CHAR) NOT NULL,
  VALOR       NUMBER(10,2)       NOT NULL,
  STATUS      VARCHAR2(20 CHAR)  NOT NULL,
  CREATED_BY  VARCHAR2(60 CHAR)  NOT NULL,
  CREATED_AT  TIMESTAMP          NOT NULL,
  CONSTRAINT PK_CONSULTA PRIMARY KEY (ID),
  CONSTRAINT CK_CONSULTA_STATUS CHECK (STATUS IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
  CONSTRAINT FK_CONSULTA_PACIENTE FOREIGN KEY (PACIENTE_ID) REFERENCES PACIENTE (ID),
  CONSTRAINT FK_CONSULTA_MEDICO FOREIGN KEY (MEDICO_ID) REFERENCES MEDICO (ID)
);

CREATE TABLE RECEITA (
  ID           NUMBER(19)         NOT NULL,
  CONSULTA_ID  NUMBER(19)         NOT NULL,
  MEDICAMENTO  VARCHAR2(100 CHAR) NOT NULL,
  POSOLOGIA    VARCHAR2(200 CHAR) NOT NULL,
  DURACAO_DIAS NUMBER(3)          NOT NULL,
  CREATED_BY   VARCHAR2(60 CHAR)  NOT NULL,
  CREATED_AT   TIMESTAMP          NOT NULL,
  CONSTRAINT PK_RECEITA PRIMARY KEY (ID),
  CONSTRAINT CK_RECEITA_DURACAO CHECK (DURACAO_DIAS BETWEEN 1 AND 365),
  CONSTRAINT FK_RECEITA_CONSULTA FOREIGN KEY (CONSULTA_ID) REFERENCES CONSULTA (ID)
);

CREATE INDEX IX_CONSULTA_PACIENTE ON CONSULTA (PACIENTE_ID);
CREATE INDEX IX_RECEITA_CONSULTA ON RECEITA (CONSULTA_ID);
